// Builds Zane's app (site root) and each friend's copy of Get Jacked (friends.json) into its own folder, e.g. ./ben/.
// The stock pages live in template/ (index.html, sw.js, manifest.webmanifest); edit those, never the generated copies.
// Root: template + the default theme (friends.json "defaultTheme", e.g. themes/jacked) + a root user.js that only names
// the theme; Zane's password, storage keys and icons stay the config.js defaults.
// A friend folder holds only what has to be per-person: index.html, user.js (password hash, storage namespace),
// manifest.webmanifest (own id/start_url/scope + car icons), sw.js (own scope, own cache) and icons/.
// All app code, CSS and exercise images are shared from the site root via ../ so every update reaches everyone:
// change the app, run `npm run build:friends` (the tests fail if the root or a friend folder is out of date), commit.
// Usage: node scripts/build-friends.mjs [--check]
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const read = (f) => fs.readFileSync(path.join(ROOT, f), "utf8");
const tpl = (f) => read("template/" + f);
const { friends, defaultTheme = "" } = JSON.parse(read("friends.json"));
export { defaultTheme };
// The theme a friends.json entry gets: its own "theme", "none" for the stock look, or (no "theme") the default theme.
export const themeOf = (f) => (f.theme === undefined ? defaultTheme : f.theme === "none" ? "" : f.theme);
const GEN = "Generated by scripts/build-friends.mjs from the root app; do not edit, run `npm run build:friends`.";
const ROOT_GEN = "Generated by scripts/build-friends.mjs from template/ + friends.json \"defaultTheme\"; do not edit, run `npm run build:friends`.";
const ICONS = ["icon-192.png", "icon-512.png", "icon-maskable-192.png", "icon-maskable-512.png", "apple-touch-icon-180.png", "favicon-32.png", "favicon-48.png", "badge-96.png"];

// Optional per-friend theme (friends.json "theme": "<name>" -> themes/<name>/theme.json): an extra stylesheet loaded
// after styles.css, an optional classic script loaded after user.js (it may set globalThis.GJ_THEME hooks, e.g. a
// Today-page layout), a body class, assets + an alternative exercise-image set precached by that friend's worker.
// Only that friend's generated files change; other friends are untouched.
// A theme may name a "base" theme: the friend then gets the base theme's stylesheet, script, assets, body class,
// exercise images and theme colour first, with this theme's own files layered on top (the base folder is reused, not copied).
// "restStrip": "right" puts the rest-day week strip in the hero's bottom-right (body class rest-strip-right); default left.
export function loadTheme(name, seen = []) {
  if (!name) return null;
  if (!/^[a-z0-9-]+$/.test(name) || seen.includes(name)) throw new Error(`bad theme name ${name}`);
  const dir = `themes/${name}/`, t = JSON.parse(read(dir + "theme.json"));
  const own = [t.css, ...(t.js ? [t.js] : []), ...(t.assets || [])].map((a) => dir + a);
  for (const file of own) if (!fs.existsSync(path.join(ROOT, file))) throw new Error(`theme ${name}: missing ${file}`);
  const b = t.base ? loadTheme(t.base, [...seen, name]) : null;
  return {
    name, ...t, dir, files: [...(b ? b.files : []), ...own],
    styles: [...(b ? b.styles : []), dir + t.css],
    scripts: [...(b ? b.scripts : []), ...(t.js ? [dir + t.js] : [])],
    // rest-day week strip side: a theme's own setting, never inherited from its base, so only themes that opt in
    // ("restStrip": "right", e.g. falcon) get it on the right; everything else (jacked, hilux, new themes) is left.
    restStrip: t.restStrip === "right" ? "right" : "left",
    classes: [...(b ? b.classes : []).filter((c) => c !== "rest-strip-right"), `theme-${name}`, ...(t.restStrip === "right" ? ["rest-strip-right"] : [])],
    exImgDir: t.exImgDir ?? b?.exImgDir, themeColor: t.themeColor ?? b?.themeColor,
  };
}
// Short content hash of everything a theme ships, so editing the theme always bumps the friend's cache version.
function themeHash(t, imgs) {
  const h = crypto.createHash("sha256");
  for (const file of [...t.files, ...imgs]) h.update(file).update(fs.readFileSync(path.join(ROOT, file)));
  return h.digest("hex").slice(0, 8);
}

export function friendFiles(f) {
  if (!/^[a-z0-9-]+$/.test(f.slug) || !/^[0-9a-f]{64}$/.test(f.passSha256)) throw new Error(`bad friend entry ${JSON.stringify(f)}`);
  const out = {};
  // index.html: the root page with shared files pointed at ../ and the friend's user.js loaded first
  let html = tpl("index.html");
  const swap = (a, b) => { if (!html.includes(a)) throw new Error(`index.html changed, can't find ${a}`); html = html.replace(a, b); };
  swap('<link rel="stylesheet" href="styles.css">', '<link rel="stylesheet" href="../styles.css">');
  swap('<script type="module" src="app.js"></script>', '<script src="user.js"></script>\n  <script type="module" src="../app.js"></script>');
  swap('<link rel="icon" href="icons/icon-192.png" type="image/png">', '<link rel="icon" href="icons/favicon-32.png" sizes="32x32" type="image/png">\n  <link rel="icon" href="icons/favicon-48.png" sizes="48x48" type="image/png">\n  <link rel="icon" href="icons/icon-192.png" sizes="192x192" type="image/png">');
  const theme = loadTheme(themeOf(f));
  if (theme) {
    swap('<link rel="stylesheet" href="../styles.css">', ['<link rel="stylesheet" href="../styles.css">', ...theme.styles.map((u) => `<link rel="stylesheet" href="../${u}">`)].join("\n  "));
    if (theme.scripts.length) swap('<script src="user.js"></script>', ['<script src="user.js"></script>', ...theme.scripts.map((u) => `<script src="../${u}"></script>`)].join("\n  "));
    swap("<body>", `<body class="${theme.classes.join(" ")}">`);
    if (theme.themeColor) swap('<meta name="theme-color" content="#111827">', `<meta name="theme-color" content="${theme.themeColor}">`);
  }
  out["index.html"] = html.replace("<!doctype html>", `<!doctype html>\n<!-- ${GEN} -->`);
  // user.js: read by config.js before the app starts
  const cfg = { user: f.slug, storagePrefix: `${f.slug}:`, passSha256: f.passSha256, assetBase: "../" };
  if (theme) cfg.theme = theme.name;
  if (theme?.exImgDir) cfg.exImgDir = theme.exImgDir;
  out["user.js"] = `// ${GEN}\n// ${f.name}'s settings. Password stored only as SHA-256 of the lower-cased password.\nwindow.GJ_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`;
  // manifest: same app, its own identity and scope so it installs as a separate app with the friend's icon
  const m = JSON.parse(tpl("manifest.webmanifest"));
  Object.assign(m, { id: "./", name: "Get Jacked", short_name: "Get Jacked", start_url: "./#/today", scope: "./" });
  if (theme?.themeColor) Object.assign(m, { theme_color: theme.themeColor, background_color: theme.themeColor });
  m.icons = [
    { src: "icons/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
    { src: "icons/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
    { src: "icons/icon-maskable-192.png", sizes: "192x192", type: "image/png", purpose: "maskable" },
    { src: "icons/icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
  ];
  m.shortcuts = (m.shortcuts || []).map((s) => ({ ...s, icons: [{ src: "icons/icon-192.png", sizes: "192x192" }] }));
  out["manifest.webmanifest"] = JSON.stringify(m, null, 2) + "\n";
  // sw.js: the root worker with its own cache name and a shell list where shared files come from ../
  let sw = tpl("sw.js");
  const ver = sw.match(/const VERSION = "([^"]+)";/)[1];
  let imgs = JSON.parse(sw.match(/const IMAGES = (\[.*?\]);/)[1]);
  if (theme?.exImgDir) {
    imgs = imgs.map((u) => u.replace(/^\.\/img\/ex\//, "./" + theme.exImgDir));
    for (const u of imgs) if (!fs.existsSync(path.join(ROOT, u))) throw new Error(`theme ${theme.name}: missing ${u.slice(2)} (python3 themes/${theme.name}/recolor-ex.py)`);
  }
  const shell = sw.match(/const SHELL = \[([\s\S]*?)\];/)[1].match(/"[^"]+"/g).map((s) => JSON.parse(s));
  const shared = shell.filter((u) => u !== "./" && u !== "./index.html" && u !== "./manifest.webmanifest" && !u.startsWith("./icons/")).map((u) => "../" + u.slice(2));
  if (theme) shared.push(...theme.files.map((u) => "../" + u));
  const own = ["./", "./index.html", "./user.js", "./manifest.webmanifest", ...ICONS.map((i) => `./icons/${i}`)];
  sw = sw.replace(/const VERSION = "[^"]+";/, `const VERSION = "${ver}-${f.slug}${theme ? `-${theme.name}-${themeHash(theme, imgs.map((u) => u.slice(2)))}` : ""}";`)
    .replace(/const IMAGES = \[.*?\];/, `const IMAGES = ${JSON.stringify(imgs.map((u) => "../" + u.slice(2)))};`)
    .replace(/const SHELL = \[[\s\S]*?\];/, `const SHELL = [\n  ${own.map((u) => JSON.stringify(u)).join(", ")},\n  ${shared.map((u) => JSON.stringify(u)).join(", ")},\n  ...IMAGES,\n];`)
    .replace(/^\/\/ Get Jacked service worker:.*$/m, (l) => `${l.replace("Get Jacked", `Get Jacked (${f.name})`)}\n// ${GEN}`);
  out["sw.js"] = sw;
  return out;
}

// Zane's app at the site root: the template pages with the default theme layered on (same paths, no ../). Only the theme
// name and its exercise-image folder go into user.js, so the password, lock and storage keys stay the config.js defaults.
export function rootFiles() {
  const theme = loadTheme(defaultTheme), out = {};
  let html = tpl("index.html"), sw = tpl("sw.js");
  if (!theme) return { "index.html": html, "sw.js": sw, "manifest.webmanifest": tpl("manifest.webmanifest") };
  const swap = (a, b) => { if (!html.includes(a)) throw new Error(`template/index.html changed, can't find ${a}`); html = html.replace(a, b); };
  swap('<link rel="stylesheet" href="styles.css">', ['<link rel="stylesheet" href="styles.css">', ...theme.styles.map((u) => `<link rel="stylesheet" href="${u}">`)].join("\n  "));
  swap('<script type="module" src="app.js"></script>', ['<script src="user.js"></script>', ...theme.scripts.map((u) => `<script src="${u}"></script>`), '<script type="module" src="app.js"></script>'].join("\n  "));
  swap("<body>", `<body class="${theme.classes.join(" ")}">`);
  if (theme.themeColor) swap('<meta name="theme-color" content="#111827">', `<meta name="theme-color" content="${theme.themeColor}">`);
  out["index.html"] = html.replace("<!doctype html>", `<!doctype html>\n<!-- ${ROOT_GEN} -->`);
  const cfg = { theme: theme.name, ...(theme.exImgDir ? { exImgDir: theme.exImgDir } : {}) };
  out["user.js"] = `// ${ROOT_GEN}\n// Zane's app (site root): only the look. Password, lock and storage keys are the config.js defaults.\nwindow.GJ_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`;
  // manifest: only the colours change (same id, name, icons and shortcuts, same layout)
  let man = tpl("manifest.webmanifest");
  if (theme.themeColor) man = man.replace(/"(background_color|theme_color)": "#[0-9a-fA-F]{3,8}"/g, `"$1": "${theme.themeColor}"`);
  out["manifest.webmanifest"] = man;
  const ver = sw.match(/const VERSION = "([^"]+)";/)[1];
  let imgs = JSON.parse(sw.match(/const IMAGES = (\[.*?\]);/)[1]);
  if (theme.exImgDir) imgs = imgs.map((u) => u.replace(/^\.\/img\/ex\//, "./" + theme.exImgDir));
  for (const u of imgs) if (!fs.existsSync(path.join(ROOT, u))) throw new Error(`theme ${theme.name}: missing ${u.slice(2)}`);
  const shell = sw.match(/const SHELL = \[([\s\S]*?)\];/)[1].match(/"[^"]+"/g).map((s) => JSON.parse(s));
  const files = [...shell, "./user.js", ...theme.files.map((u) => "./" + u)];
  out["sw.js"] = sw.replace(/const VERSION = "[^"]+";/, `const VERSION = "${ver}-${theme.name}-${themeHash(theme, imgs.map((u) => u.slice(2)))}";`)
    .replace(/const IMAGES = \[.*?\];/, `const IMAGES = ${JSON.stringify(imgs)};`)
    .replace(/const SHELL = \[[\s\S]*?\];/, `const SHELL = [\n  ${files.map((u) => JSON.stringify(u)).join(", ")},\n  ...IMAGES,\n];`)
    .replace(/^\/\/ Get Jacked service worker:.*$/m, (l) => `${l}\n// ${ROOT_GEN}`);
  return out;
}

export function build({ check = false } = {}) {
  const stale = [];
  for (const [name, text] of Object.entries(rootFiles())) {
    const p = path.join(ROOT, name);
    if (fs.existsSync(p) && fs.readFileSync(p, "utf8") === text) continue;
    if (check) stale.push(name); else { fs.writeFileSync(p, text); console.log("wrote", name); }
  }
  for (const f of friends) {
    const dir = path.join(ROOT, f.slug);
    for (const i of ICONS) if (!fs.existsSync(path.join(dir, "icons", i))) stale.push(`${f.slug}/icons/${i} missing (python3 scripts/friend-icons.py ${f.slug})`);
    for (const [name, text] of Object.entries(friendFiles(f))) {
      const p = path.join(dir, name);
      if (fs.existsSync(p) && fs.readFileSync(p, "utf8") === text) continue;
      if (check) stale.push(`${f.slug}/${name}`); else { fs.mkdirSync(dir, { recursive: true }); fs.writeFileSync(p, text); console.log("wrote", `${f.slug}/${name}`); }
    }
  }
  return stale;
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  const check = process.argv.includes("--check"), stale = build({ check });
  if (stale.length) { console.error((check ? "Out of date: " : "Problems: ") + stale.join(", ")); process.exit(1); }
  console.log(check ? "root + friend folders up to date" : "root + friend folders built: " + friends.map((f) => f.slug + "/").join(" "));
}
